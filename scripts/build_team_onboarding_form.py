def render_team_update_page(cfg: dict) -> Path:
    template_html = TEMPLATE_FILE.read_text(encoding="utf-8")
    club_json_str = json.dumps(cfg, ensure_ascii=False)

    replacements = {
        "{{CLUB_NAME}}": cfg["club_name"],
        "{{CLUB_SUB}}": cfg["club_sub"],
        "{{LOGO_PATH}}": cfg["logo_path"],
        "{{SITE_ID}}": cfg["site_id"],
        "{{TEAM_COUNT}}": str(len(cfg["teams"])),
        "{{DEFAULT_TEAM_PHOTO}}": cfg["default_team_photo"],
        "{{BRAND_PRIMARY}}": cfg["brand_primary"],
        "{{BRAND_PRIMARY_DARK}}": cfg["brand_primary_dark"],
        "{{BRAND_PRIMARY_SOFT}}": cfg["brand_primary_soft"],
        "{{BRAND_NAVY}}": cfg["brand_navy"],
        "{{BRAND_GOLD}}": cfg["brand_gold"],
        "{{BRAND_GOLD_SOFT}}": cfg["brand_gold_soft"],
        "{{CLUB_DATA_JSON}}": club_json_str,
    }

    html = template_html
    for k, v in replacements.items():
        html = html.replace(k, v)

    # Helvetischer Standard Guard (100 % ss statt Eszett)
    html = html.replace("\u00df", "ss")

    out_path = BASE_DIR / cfg["target_dir"] / "team-update.html"
    out_path.write_text(html, encoding="utf-8")
    return out_path


